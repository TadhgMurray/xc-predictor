#!/usr/bin/env python3
"""
gender_pace_pin.py -- a men's cross country race filed at the women's
distance, found from the two races' own times. Pipeline step 04g0.

    python engine/gender_pace_pin.py            # dry run: what it would pin
    python engine/gender_pace_pin.py --write    # rewrite its block in corrections.py

★ THE CASE (owner, 2026-10-13). Al Shirley Invitational 2026, Pima CC West:
  two "Collegiate" divisions, both stored at 5000 m. Women (div 1145428,
  13 rows) median 23:17; men (div 1145427, 25 rows) median 35:40. College
  men do not run thirteen minutes slower than college women over the same
  ground: the men ran the junior college 8K. Sharing one "5000 m" course
  with them, the women's real 5K was credited +35% of course plus a capped
  slow day, and rated 152-167.

★ THE RULE. At one meet and one STORED distance, a men's division and the
  women's division with the most finishers. At equal distance women run
  about F_OVER_M (1.15) times the men's time; so when the men's median is
  more than GAP (15%) SLOWER than the women's -- a gap no level difference
  inside one meet makes -- the men ran farther, by

      D = d * (t_men * F_OVER_M / t_women) ** (1 / K)

  snapped to a standard cross country distance within SNAP_TOL. Pinned
  only when the snap is a real distance longer than the stored one.
  Al Shirley: 35.67 * 1.15 / 23.28 = 1.762 -> 5000 * 1.762^(1/1.06) =
  8,530 m -> 8000.

! ONE DIRECTION ONLY. Men longer than stored is the common shape (8K and
  6K college men, women at 5K or 6K); "women shorter than stored" reads the
  same from the times and is left alone -- the two cannot be told apart by
  this rule, and a pin on the wrong side would move a correct race.
! ITS OWN BLOCK, REWRITTEN WHOLE. corrections.py carries the pins between
  BLOCK_START and BLOCK_END, replaced on every --write, so a race that
  stops qualifying loses its pin. A hand-written override for the same
  division wins (dump_overrides' precedence ranks this dict after
  _DISTANCE_OVERRIDES_XC), and 04g's audit can still remove a pin the
  field rejects.
"""
import io
import os
import re
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
for _p in (_HERE, os.path.join(os.path.dirname(_HERE), "scripts")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

PATH = os.path.join(_HERE, "corrections.py")
BLOCK_START = "# --- generated by gender_pace_pin.py ---"
BLOCK_END = "# --- end gender_pace_pin.py ---"

F_OVER_M = 1.15          # women's time over men's at equal distance
GAP = 1.15               # men's median this much over the women's = not one distance
K = 1.06                 # the distance exponent the proposers use
SNAP_TOL = 0.08
MIN_ROWS = 8
STANDARD = (3000.0, 3218.0, 4000.0, 4828.0, 5000.0, 6000.0, 6437.0,
            8000.0, 10000.0)

_SQL = """
    SELECT r.meet_id, r.div_id, m.distance::float, max(m.course_name),
           mode() WITHIN GROUP (ORDER BY a.gender) FILTER (WHERE a.gender IN ('M', 'F')),
           count(*), percentile_cont(0.5) WITHIN GROUP (ORDER BY r.time_seconds)
    FROM   results r
    JOIN   meets m ON m.div_id = r.div_id AND m.meet_id = r.meet_id
    LEFT   JOIN athletes a ON a.athlete_id = r.athlete_id
    WHERE  r.source = 'anet' AND r.time_seconds > 0 AND r.time_seconds < 10000
      AND  m.distance BETWEEN 2000 AND 8100
    GROUP  BY r.meet_id, r.div_id, m.distance
    HAVING count(*) >= %s
"""


def snap(d):
    best = min(STANDARD, key=lambda s: abs(s - d))
    return best if abs(best - d) <= SNAP_TOL * best else None


def pins(rows):
    """[(meet, div, stored, pinned, why)] from (meet, div, stored, course,
    gender, n, median_s) rows. Pure."""
    by = {}
    for meet, div, dist, course, g, n, med in rows:
        if g in ("M", "F") and dist and med:
            by.setdefault((meet, round(float(dist))), []).append(
                (div, g, int(n), float(med), course))
    out = []
    for (meet, dist), divs in by.items():
        women = [d for d in divs if d[1] == "F"]
        if not women:
            continue
        w = max(women, key=lambda d: d[2])
        for div, g, n, t_m, course in divs:
            if g != "M" or t_m <= w[3] * GAP:
                continue
            implied = dist * (t_m * F_OVER_M / w[3]) ** (1.0 / K)
            s = snap(implied)
            if s is None or s <= dist * 1.1:
                continue
            out.append((meet, div, dist, s,
                        f"men {t_m / 60:.2f} min vs women {w[3] / 60:.2f} (div {w[0]}) "
                        f"at {dist} m; implied {implied:,.0f} -- {course or ''}"))
    return sorted(out)


def block(found):
    lines = [BLOCK_START,
             "# men's XC divisions stored at the women's distance, pinned from",
             "# the two races' medians (engine/gender_pace_pin.py). Rewritten whole.",
             "_DISTANCE_PIN_GENDER = {"]
    for meet, div, dist, s, why in found:
        lines.append(f"    ({meet}, {div}): {s:g},  # was {dist}: {why}")
    # ! MERGED INTO THE DICT THE BACKFILL READS (_DISTANCE_OVERRIDES_BY_SPORT
    #   ["XC"]); a dict of its own reaches dump_overrides' table but not the
    #   backfill. setdefault: a hand-written override for the key wins.
    lines += ["}",
              "for _k, _v in _DISTANCE_PIN_GENDER.items():",
              "    _DISTANCE_OVERRIDES_BY_SPORT['XC'].setdefault(_k, _v)",
              BLOCK_END]
    return "\n".join(lines) + "\n"


def replaceBlock(text, new_block):
    pat = re.compile(re.escape(BLOCK_START) + r".*?" + re.escape(BLOCK_END) + r"\n?",
                     re.S)
    if pat.search(text):
        return pat.sub(lambda _m: new_block, text, count=1)
    return text.rstrip("\n") + "\n\n" + new_block


def main():
    write = "--write" in sys.argv
    from database import getConn
    with getConn() as c, c.cursor() as cur:
        cur.execute(_SQL, (MIN_ROWS,))
        found = pins(cur.fetchall())
    print(f"[gender_pin] {len(found):,} men's divisions slower than their meet's "
          f"women at the same stored distance by more than {100 * (GAP - 1):.0f}%")
    for meet, div, dist, s, why in found[:20]:
        print(f"    {meet}/{div}: {dist} -> {s:g}  ({why})")
    if not write:
        print("[gender_pin] DRY RUN -- --write rewrites the block in corrections.py")
        return
    if not os.path.exists(PATH):
        print(f"[gender_pin] {PATH} missing -- nothing written")
        return
    text = io.open(PATH, encoding="utf-8", newline="").read()
    io.open(PATH, "w", encoding="utf-8", newline="").write(replaceBlock(text, block(found)))
    print(f"[gender_pin] wrote {len(found):,} pins to {PATH}")


if __name__ == "__main__":
    main()
