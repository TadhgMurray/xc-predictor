#!/usr/bin/env python3
"""
data_checks.py -- the data checks, one pipeline step (04g1), fixes included.

    python engine/data_checks.py            # dry run: the issues, nothing written
    python engine/data_checks.py --write    # data_issue table + the pins block

(owner, 2026-10-13: "there are so many small data leaks ... wrong distance,
wrong parser, wrong gender, wrong age ... just a pipeline step that can be
fixed.") Every one of the day's bugs was TWO FACTS THAT SHOULD AGREE AND DID
NOT. Each check here is one such pair, run on every pipeline run against
the previous run's numbers, before the backfill that would carry a fix:

  race_field   a race against its own runners. The median, over a
               division's runners, of (rating here / the runner's own
               typical rating - 1). A whole field 15%+ off its own level,
               most of it the same way, is the race, not the runners: a
               wrong distance, a wrong course, a misread sheet (9%: where
               field_shift measured normal racing ends).
               FIX (cross country, athletic.net): the distance the gap
               implies, snapped to a standard one -- only when another
               division of the SAME MEET is stored at that distance (the
               corroboration propose_distances uses). Pins are STICKY (a
               fixed race no longer shows the gap, so a rewritten block
               would drop its own fix); 04g's audit removes a pin the field
               rejects. Anything else is listed for review.
  parser       two parsers of one event name. event_parse (normalized_time)
               against speed_ratings_db._eventMetersSql (the pack's
               distance) on every distinct track event_short: a
               disagreement is the 880-yard bug's shape. Listed.
  person_gender one person, both genders: the athlete rows a person holds
               carry both M and F. A merged identity. Listed.

The table `data_issue` is replaced whole each run, ranked by IMPACT (rows
times the size of the disagreement), so the top of it is what moves the
most ratings.
"""
import io
import os
import re
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
for _p in (_HERE, os.path.join(os.path.dirname(_HERE), "scripts")):
    if _p not in sys.path:
        sys.path.insert(0, _p)

PATH = os.path.join(_HERE, "corrections.py")
BLOCK_START = "# --- generated by data_checks.py (sticky) ---"
BLOCK_END = "# --- end data_checks.py ---"

K = 1.06                  # the distance exponent the proposers use
# ★ 9%, NOT 15% (the first cut missed its own example: Hole in the Wall read
#   8-12% under, a 4506-for-5000 error is 11.6%). field_shift measured where
#   normal racing ends: the field-gap histogram decays to +8 points and turns
#   into a flat shelf at +9 -- a second population. Corroboration still gates
#   every pin; below the share bar nothing is listed at all.
FIELD_GAP = 0.09          # a field this far off its own level is the race
FIELD_SHARE = 0.70        # ... with this share of its runners off the same way
FIELD_MIN = 8             # runners with a baseline, before a field testifies
BASE_MIN = 5              # rated races before a runner has a baseline
SNAP_TOL = 0.06
CORROB_TOL = 0.02
STANDARD = (1609.0, 2000.0, 2414.0, 3000.0, 3218.0, 4000.0, 4828.0,
            5000.0, 6000.0, 6437.0, 8000.0, 10000.0)

_DDL = """
    CREATE TABLE IF NOT EXISTS data_issue (
        kind        text,
        sport       text,
        key         text,
        n_rows      integer,
        magnitude   real,
        impact      real,
        evidence    text,
        action      text,
        created_at  timestamptz DEFAULT now())
"""


# ------------------------------------------------------------------ #
#  pure parts
# ------------------------------------------------------------------ #

def snap(d, tol=SNAP_TOL):
    best = min(STANDARD, key=lambda s: abs(s - d))
    return best if abs(best - d) <= tol * best else None


def impliedDistance(stored, gap):
    """The distance a field `gap` off its level (rating ratio - 1) ran, if
    the stored distance is the error: rating scales as (d_stored/d_true)^K."""
    return stored * (1.0 + gap) ** (-1.0 / K)


def fieldVerdict(row, meet_distances):
    """(action, pinned_distance or None, evidence) for one division's row
    (meet, div, source, stored, n, gap, share_up, share_down)."""
    meet, div, source, stored, n, gap, up, down = row
    share = up if gap > 0 else down
    ev = (f"{n} runners, field {100 * gap:+.1f}% vs their own level "
          f"({100 * share:.0f}% of them the same way)")
    if source != "anet" or not stored:
        return "review", None, ev + "; no stored anet distance to fix"
    implied = impliedDistance(float(stored), gap)
    s = snap(implied)
    ev += f"; stored {float(stored):g} m implies {implied:,.0f}"
    if s is None or abs(s - float(stored)) <= CORROB_TOL * s:
        return "review", None, ev + " (no standard distance there)"
    sibs = [d for d in meet_distances.get(meet, ()) if d and abs(d - s) <= CORROB_TOL * s]
    if not sibs:
        return "review", None, ev + f" -> {s:g}, but no other division of the meet runs it"
    return "pin", s, ev + f" -> {s:g}, as another division of the meet"


def fieldCandidates(rows):
    """Rows past the gap and share bars. Pure."""
    out = []
    for r in rows:
        _m, _d, _s, _st, n, gap, up, down = r
        if n is None or gap is None or n < FIELD_MIN or abs(gap) < FIELD_GAP:
            continue
        if (up if gap > 0 else down) < FIELD_SHARE:
            continue
        out.append(r)
    return out


def readPins(text):
    """{(meet, div): distance} already in the sticky block."""
    m = re.search(re.escape(BLOCK_START) + r"(.*?)" + re.escape(BLOCK_END), text, re.S)
    if not m:
        return {}
    return {(int(a), int(b)): float(c) for a, b, c in
            re.findall(r"\((\d+),\s*(\d+)\):\s*([0-9.]+)", m.group(1))}


def block(pins):
    lines = [BLOCK_START,
             "# XC divisions whose whole field ran 15%+ off its own level, pinned to",
             "# the distance that gap implies when another division of the same meet",
             "# runs it (engine/data_checks.py). STICKY: kept until 04g's audit",
             "# removes one; a hand-written override for the key wins.",
             "_DISTANCE_PIN_FIELD = {"]
    for (meet, div), d in sorted(pins.items()):
        lines.append(f"    ({meet}, {div}): {d:g},")
    lines += ["}",
              "for _k, _v in _DISTANCE_PIN_FIELD.items():",
              "    _DISTANCE_OVERRIDES_BY_SPORT['XC'].setdefault(_k, _v)",
              BLOCK_END]
    return "\n".join(lines) + "\n"


def replaceBlock(text, new_block):
    pat = re.compile(re.escape(BLOCK_START) + r".*?" + re.escape(BLOCK_END) + r"\n?", re.S)
    if pat.search(text):
        return pat.sub(lambda _m: new_block, text, count=1)
    return text.rstrip("\n") + "\n\n" + new_block


def parserIssues(pairs, tol=0.01):
    """[(event, python_m, sql_m)] where the two parsers disagree; rows the
    Python parser does not rate (None) are not the pack's concern. Pure."""
    out = []
    for ev, py_m, sql_m in pairs:
        if py_m is None:
            continue
        if sql_m is None or abs(float(sql_m) - float(py_m)) > tol * float(py_m):
            out.append((ev, py_m, sql_m))
    return out


# ------------------------------------------------------------------ #
#  the checks against the database
# ------------------------------------------------------------------ #

def raceField(cur):
    cur.execute("""
        CREATE TEMP TABLE dc_base ON COMMIT DROP AS
        SELECT person_id, exp(avg(ln(speed_rating))) AS b
        FROM  (SELECT person_id, speed_rating FROM results
               WHERE speed_rating > 0 AND person_id IS NOT NULL
               UNION ALL
               SELECT person_id, speed_rating FROM results_tf
               WHERE speed_rating > 0 AND person_id IS NOT NULL) x
        GROUP BY person_id HAVING count(*) >= %s""", (BASE_MIN,))
    cur.execute("CREATE INDEX ON dc_base (person_id)")
    cur.execute("""
        SELECT r.meet_id, r.div_id, r.source, max(m.distance)::float, count(*),
               percentile_cont(0.5) WITHIN GROUP (ORDER BY r.speed_rating / b.b - 1),
               avg(((r.speed_rating / b.b - 1) > 0.05)::int),
               avg(((r.speed_rating / b.b - 1) < -0.05)::int)
        FROM   results r
        JOIN   dc_base b ON b.person_id = r.person_id
        LEFT   JOIN meets m ON r.source = 'anet' AND m.meet_id = r.meet_id
                           AND m.div_id = r.div_id
        WHERE  r.speed_rating > 0
        GROUP  BY r.meet_id, r.div_id, r.source
        HAVING count(*) >= %s""", (FIELD_MIN,))
    cands = fieldCandidates(cur.fetchall())
    meets = sorted({c[0] for c in cands if c[2] == "anet"})
    md = {}
    if meets:
        cur.execute("""SELECT meet_id, array_agg(DISTINCT distance::float)
                       FROM meets WHERE meet_id = ANY(%s) GROUP BY 1""", (meets,))
        md = {m: list(ds or []) for m, ds in cur.fetchall()}
    issues, pins = [], {}
    for c in cands:
        action, s, ev = fieldVerdict(c, md)
        meet, div, source, stored, n, gap = c[:6]
        if action == "pin":
            pins[(int(meet), int(div))] = s
        issues.append(("race_field", "XC", f"{source} {meet}/{div}", int(n),
                       float(gap), int(n) * abs(float(gap)), ev, action))
    return issues, pins


def parser(cur):
    import event_parse as ep
    import speed_ratings_db as sdb
    cur.execute(f"""SELECT r.event_short, {sdb._eventMetersSql('r')}
                    FROM (SELECT DISTINCT event_short FROM results_tf
                          WHERE event_short IS NOT NULL) r""")
    pairs = []
    for ev, sql_m in cur.fetchall():
        py = ep.distanceFromEventShort(ev)
        py = py[0] if isinstance(py, tuple) else py
        pairs.append((ev, py, sql_m))
    out = []
    for ev, py_m, sql_m in parserIssues(pairs):
        cur.execute("SELECT count(*) FROM results_tf WHERE event_short = %s", (ev,))
        n = int(cur.fetchone()[0])
        mag = (abs(float(sql_m) / float(py_m) - 1) if sql_m else 1.0)
        out.append(("parser", "TF", ev, n, mag, n * mag,
                    f"event_parse {py_m} m vs the pack's SQL {sql_m} m", "review"))
    return out


def personGender(cur):
    cur.execute("""
        SELECT r.person_id, count(*),
               count(*) FILTER (WHERE a.gender = 'M'), count(*) FILTER (WHERE a.gender = 'F')
        FROM   results r JOIN athletes a ON r.source = 'anet' AND a.athlete_id = r.athlete_id
        WHERE  r.person_id IS NOT NULL AND a.gender IN ('M', 'F')
        GROUP  BY r.person_id
        HAVING count(DISTINCT a.gender) > 1""")
    out = []
    for pid, n, m, f in cur.fetchall():
        minority = min(m, f)
        out.append(("person_gender", "XC", f"person {pid}", int(n),
                    minority / max(n, 1), float(minority),
                    f"{m} rows on men's athlete records, {f} on women's", "review"))
    return out


def main():
    write = "--write" in sys.argv
    from database import getConn
    issues, pins = [], {}
    with getConn() as c, c.cursor() as cur:
        for name, fn in (("race_field", raceField), ("parser", parser),
                         ("person_gender", personGender)):
            try:
                got = fn(cur)
                if name == "race_field":
                    got, pins = got
                issues += got
                print(f"[data_checks] {name}: {len(got):,} issues", flush=True)
            except Exception as exc:                          # noqa: BLE001
                c.rollback()
                print(f"[data_checks] {name}: NOT RUN ({type(exc).__name__}: {exc})")
        issues.sort(key=lambda t: -t[5])
        for kind, sport, key, n, mag, imp, ev, act in issues[:30]:
            print(f"    {kind:<14} {key:<28} {act:<6} impact {imp:8.1f}  {ev}")
        if not write:
            c.rollback()
            print(f"[data_checks] DRY RUN -- {len(pins):,} pins would be added")
            return
        cur.execute(_DDL)
        cur.execute("DELETE FROM data_issue")
        if issues:
            from psycopg2.extras import execute_values
            execute_values(cur, """INSERT INTO data_issue (kind, sport, key, n_rows,
                                   magnitude, impact, evidence, action) VALUES %s""",
                           issues)
        c.commit()
    print(f"[data_checks] data_issue: {len(issues):,} rows")
    if os.path.exists(PATH):
        text = io.open(PATH, encoding="utf-8", newline="").read()
        old = readPins(text)
        merged = dict(old)
        for k, v in pins.items():
            merged.setdefault(k, v)
        io.open(PATH, "w", encoding="utf-8", newline="").write(replaceBlock(text, block(merged)))
        print(f"[data_checks] pins: {len(merged) - len(old):,} new, {len(merged):,} in the block")
    else:
        print(f"[data_checks] {PATH} missing -- pins not written")


if __name__ == "__main__":
    main()
