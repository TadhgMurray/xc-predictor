def _base(cur):
    """dc_base(person_id, pool, b): each runner's typical rating IN ONE
    POOL, once a run.

    ★ PER POOL, NOT PER CAREER (owner, 2026-10-19: Catholic Athletic League
      State Championship 2019, a 2-mile race of 5th-8th graders pinned to
      1609 m -- a 6th grader's winning 11:25.8 "verified" as a mile). A
      speed_rating is on its row's OWN pool's scale (100 = that pool's
      average runner), so one mean over elementary, middle-school and
      high-school rows is no runner's level at all. For a child who later
      raced in high school it read the whole field about twice its "own
      level", and twice the rating is half the distance: 3218 snapped to
      1609, corroborated by the meet's own mile race for the little ones.
      Within one pool the scale is one scale."""
    cur.execute("SELECT to_regclass('pg_temp.dc_base')")
    if cur.fetchone()[0] is not None:
        return
    cur.execute("""
        CREATE TEMP TABLE dc_base ON COMMIT DROP AS
        SELECT person_id, pool, exp(avg(ln(speed_rating))) AS b
        FROM  (SELECT person_id, rating_pool AS pool, speed_rating FROM results
               WHERE speed_rating > 0 AND person_id IS NOT NULL
                 AND rating_pool IS NOT NULL
               UNION ALL
               SELECT person_id, rating_pool, speed_rating FROM results_tf
               WHERE speed_rating > 0 AND person_id IS NOT NULL
                 AND rating_pool IS NOT NULL) x
        GROUP BY person_id, pool HAVING count(*) >= %s""", (BASE_MIN,))
    cur.execute("CREATE INDEX ON dc_base (person_id, pool)")


def raceField(cur):
    _base(cur)
    # ★ TFRRS TOO (2026-10-23): its stored distance is the division's entry
    #   in meets_tfrrs.division_distances, keyed by the div_id ordinal as
    #   text -- speed_ratings_db._xcQuery's own expression.
    cur.execute("""
        SELECT r.meet_id, r.div_id, r.source,
               COALESCE(max(m.distance)::float,
                        max((mt.division_distances -> r.div_id::text ->> 'distance')::float)),
               count(*),
               percentile_cont(0.5) WITHIN GROUP (ORDER BY r.speed_rating / b.b - 1),
               avg(((r.speed_rating / b.b - 1) > 0.05)::int),
               avg(((r.speed_rating / b.b - 1) < -0.05)::int)
        FROM   results r
        JOIN   dc_base b ON b.person_id = r.person_id AND b.pool = r.rating_pool
        LEFT   JOIN meets m ON r.source = 'anet' AND m.meet_id = r.meet_id
                           AND m.div_id = r.div_id
        LEFT   JOIN meets_tfrrs mt ON r.source = 'tfrrs' AND mt.meet_id = r.meet_id
                                  AND mt.sport = 'XC'
                                  AND jsonb_typeof(mt.division_distances) = 'object'
        WHERE  r.speed_rating > 0
        GROUP  BY r.meet_id, r.div_id, r.source
        HAVING count(*) >= %s""", (FIELD_MIN,))
    allrows = cur.fetchall()
    cands = fieldCandidates(allrows)
    venues = venueGaps(cur, allrows, cands)
    # ★ A PIN THE FIELD STILL REJECTS COMES OFF (2026-10-19). Pins are
    #   sticky because a fixed race stops showing its gap. So a PINNED race
    #   that still reads 9%+ off its own level was not fixed by its pin --
    #   a wrong pin shows the gap the other way (the Catholic League's
    #   2 miles pinned to 1609 rates its field at half their level). Every
    #   race past the bars goes back to main, which drops the ones it had
    #   pinned and lets the next run judge them at their stored distance.
    rejects = {pinKey(c[2], c[0], c[1]) for c in cands if c[2] in ("anet", "tfrrs")}
    meets = sorted({c[0] for c in cands if c[2] == "anet"})
    tmeets = sorted({c[0] for c in cands if c[2] == "tfrrs"})
    md = {}
    if meets:
        cur.execute("""SELECT meet_id, array_agg(DISTINCT distance::float)
                       FROM meets WHERE meet_id = ANY(%s) GROUP BY 1""", (meets,))
        md.update({("anet", m): list(ds or []) for m, ds in cur.fetchall()})
    if tmeets:
        cur.execute("""SELECT mt.meet_id, array_agg(DISTINCT (kv.value ->> 'distance')::float)
                       FROM meets_tfrrs mt,
                            LATERAL jsonb_each(CASE WHEN jsonb_typeof(mt.division_distances) = 'object'
                                                    THEN mt.division_distances ELSE '{}'::jsonb END) kv
                       WHERE mt.sport = 'XC' AND mt.meet_id = ANY(%s) GROUP BY 1""", (tmeets,))
        md.update({("tfrrs", m): list(ds or []) for m, ds in cur.fetchall()})
    issues, pins = [], {}
    for c in cands:
        meet, div, source, stored, n, gap = c[:6]
        # a sibling is ANOTHER division: this one's own stored label is not one
        sib = dict(md)
        if (source, meet) in sib:
            sib[(source, meet)] = [d for d in sib[(source, meet)]
                                   if not (stored and abs(d - float(stored)) < 1)] or []
        action, s, ev = fieldVerdict(c, sib, venues.get((source, meet, div)))
        if action == "pin":
            pins[pinKey(source, meet, div)] = s
        issues.append(("race_field", "XC", f"{source} {meet}/{div}", int(n),
                       float(gap), int(n) * abs(float(gap)), ev, action))
    return issues, pins, rejects


def venueGaps(cur, allrows, cands):
    """{(source, meet, div): (n other races at the course, their median field
    gap)} for the strong candidates only: the course is meets.course_name
    (anet) or meets_tfrrs.venue_name (tfrrs); "other" means another meet."""
    strong = [c for c in cands if c[5] is not None and c[5] >= STRONG_GAP]
    if not strong:
        return {}
    gap = {(r[2], int(r[0]), int(r[1])): float(r[5]) for r in allrows if r[5] is not None}
    a_meets = sorted({int(r[0]) for r in allrows if r[2] == "anet"})
    t_meets = sorted({int(r[0]) for r in allrows if r[2] == "tfrrs"})
    course = {}
    if a_meets:
        cur.execute("""SELECT meet_id, div_id, lower(btrim(max(course_name))) FROM meets
                       WHERE meet_id = ANY(%s) AND course_name IS NOT NULL GROUP BY 1, 2""", (a_meets,))
        course.update({("anet", int(m), int(d)): c for m, d, c in cur.fetchall() if c})
    if t_meets:
        cur.execute("""SELECT meet_id, lower(btrim(max(venue_name))) FROM meets_tfrrs
                       WHERE sport = 'XC' AND meet_id = ANY(%s) AND venue_name IS NOT NULL
                       GROUP BY 1""", (t_meets,))
        tv = {int(m): c for m, c in cur.fetchall() if c}
        course.update({k: tv[k[1]] for k in gap if k[0] == "tfrrs" and k[1] in tv})
    by_course = {}
    for k, c in course.items():
        if k in gap:
            by_course.setdefault(c, []).append(k)
    out = {}
    import statistics
    for c in strong:
        key = (c[2], int(c[0]), int(c[1]))
        here = course.get(key)
        if not here:
            continue
        others = [gap[k] for k in by_course.get(here, ()) if k[1] != key[1]]
        if others:
            out[key] = (len(others), statistics.median(others))
    return out


_VENUE_SQL = """
    CREATE TEMP TABLE dc_venue ON COMMIT DROP AS
    SELECT m.meet_id, m.div_id, max(m.distance)::float AS distance,
           max(cc.canonical_id) AS cid
    FROM   meets m
    JOIN   course_canonical cc
           ON cc.course_name = m.course_name
          AND round(cc.gps_lat::numeric,  5) = round(m.gps_lat::numeric,  5)
          AND round(cc.gps_long::numeric, 5) = round(m.gps_long::numeric, 5)
    WHERE  m.distance > 0
    GROUP  BY m.meet_id, m.div_id
"""


def venueLabel(cur):
    """Divisions stored at a venue's longer label that run like its
    shorter one (see the header). Returns (issues, pins); pins is always
    empty -- listed for review only."""
    _base(cur)
    cur.execute("DROP TABLE IF EXISTS dc_venue")
    cur.execute(_VENUE_SQL)
    cur.execute("CREATE INDEX ON dc_venue (meet_id, div_id)")
    # each venue's own labels: rows and seasons behind each stored distance
    cur.execute("""
        SELECT v.cid, v.distance, count(*), count(DISTINCT left(r.date::text, 4))
        FROM   dc_venue v
        JOIN   results r ON r.source = 'anet' AND r.meet_id = v.meet_id
                        AND r.div_id = v.div_id
        GROUP  BY 1, 2""")
    labels = {}
    for cid, d, n, yrs in cur.fetchall():
        labels.setdefault(cid, []).append((float(d), int(n), int(yrs)))
    cur.execute("""
        SELECT v.meet_id, v.div_id, v.cid, v.distance, count(*),
               percentile_cont(0.5) WITHIN GROUP (ORDER BY r.speed_rating / b.b - 1),
               avg(((r.speed_rating / b.b - 1) > 0)::int)
        FROM   dc_venue v
        JOIN   results r ON r.source = 'anet' AND r.meet_id = v.meet_id
                        AND r.div_id = v.div_id
        JOIN   dc_base b ON b.person_id = r.person_id AND b.pool = r.rating_pool
        WHERE  r.speed_rating > 0
        GROUP  BY 1, 2, 3, 4
        HAVING count(*) >= %s""", (FIELD_MIN,))
    issues, pins = [], {}
    for meet, div, cid, stored, n, gap, up in cur.fetchall():
        d, ev = venueLabelVerdict(stored, int(n), float(gap), float(up),
                                  labels.get(cid, ()))
        if d is None:
            continue
        issues.append(("venue_label", "XC", f"anet {meet}/{div}", int(n),
                       float(gap), int(n) * float(gap), ev, "review"))
    return issues, pins


def parser(cur):
    import event_parse as ep
    import speed_ratings_db as sdb
    # ! THE ROW COUNTS IN THE SAME PASS (2026-10-18): a count(*) per flagged
    #   event was one more full scan of results_tf each (no event_short index)
    cur.execute(f"""SELECT r.event_short, {sdb._eventMetersSql('r')}, r.n
                    FROM (SELECT event_short, count(*) AS n FROM results_tf
                          WHERE event_short IS NOT NULL GROUP BY 1) r""")
    pairs, counts = [], {}
    for ev, sql_m, n in cur.fetchall():
        py = ep.distanceFromEventShort(ev)
        py = py[0] if isinstance(py, tuple) else py
        pairs.append((ev, py, sql_m))
        counts[ev] = int(n)
    out = []
    for ev, py_m, sql_m in parserIssues(pairs):
        n = counts.get(ev, 0)
        mag = (abs(float(sql_m) / float(py_m) - 1) if sql_m else 1.0)
        out.append(("parser", "TF", ev, n, mag, n * mag,
                    f"event_parse {py_m} m vs the pack's SQL {sql_m} m", "review"))
    return out


def personGender(cur):
    cur.execute("""
        SELECT r.person_id, count(*),
               count(*) FILTER (WHERE a.gender = 'M'), count(*) FILTER (WHERE a.gender = 'F')
        FROM   results r JOIN athletes a ON r.source = 'anet' AND a.athlete_id = r.athlete_id
        WHERE  r.person_id IS NOT NULL AND a.gender IN ('M', 'F')
        GROUP  BY r.person_id
        HAVING count(DISTINCT a.gender) > 1""")
    out = []
    for pid, n, m, f in cur.fetchall():
        minority = min(m, f)
        out.append(("person_gender", "XC", f"person {pid}", int(n),
                    minority / max(n, 1), float(minority),
                    f"{m} rows on men's athlete records, {f} on women's", "review"))
    return out


def main():
    import time
    write = "--write" in sys.argv
    from database import getConn
    if "--purge-label-pins" in sys.argv:
        return purgeLabelPins(getConn)
    issues, pins, rejects = [], {}, set()
    t0 = time.time()
    with getConn() as c, c.cursor() as cur:
        # ★ SAY WHAT IT IS DOING (owner, 2026-10-18: "30 minutes and printed
        #   nothing"). Each check is one or two whole-table aggregates; the
        #   first builds every runner's typical rating over both result
        #   tables. A line as each starts, and the time it took.
        for name, fn in (("race_field", raceField), ("venue_label", venueLabel),
                         ("parser", parser), ("person_gender", personGender)):
            if name == "race_field":
                print("[data_checks] typical ratings (both result tables) ...", flush=True)
                try:
                    _base(cur)
                    print(f"[data_checks]   done ({time.time() - t0:.0f}s)", flush=True)
                except Exception as exc:                      # noqa: BLE001
                    c.rollback()        # the checks that need it say NOT RUN below
                    print(f"[data_checks]   failed ({type(exc).__name__}: {exc})", flush=True)
            print(f"[data_checks] {name} ...", flush=True)
            try:
                got = fn(cur)
                if name == "race_field":
                    got, more, rejects = got
                    for k, v in more.items():
                        pins.setdefault(k, v)
                elif name == "venue_label":
                    got, more = got
                    for k, v in more.items():
                        pins.setdefault(k, v)
                issues += got
                print(f"[data_checks] {name}: {len(got):,} issues "
                      f"({time.time() - t0:.0f}s)", flush=True)
            except Exception as exc:                          # noqa: BLE001
                c.rollback()
                print(f"[data_checks] {name}: NOT RUN ({type(exc).__name__}: {exc})")
        issues.sort(key=lambda t: -t[5])
        for kind, sport, key, n, mag, imp, ev, act in issues[:30]:
            print(f"    {kind:<14} {key:<28} {act:<6} impact {imp:8.1f}  {ev}")
        if not write:
            c.rollback()
            print(f"[data_checks] DRY RUN -- {len(pins):,} pins would be added")
            return
        old_text = io.open(PATH, encoding="utf-8", newline="").read() if os.path.exists(PATH) else ""
        label = labelPins(cur, readPins(old_text))
        cur.execute(_DDL)
        cur.execute("DELETE FROM data_issue")
        if issues:
            from psycopg2.extras import execute_values
            execute_values(cur, """INSERT INTO data_issue (kind, sport, key, n_rows,
                                   magnitude, impact, evidence, action) VALUES %s""",
                           issues)
        c.commit()
    print(f"[data_checks] data_issue: {len(issues):,} rows")
    if os.path.exists(PATH):
        text = io.open(PATH, encoding="utf-8", newline="").read()
        old = readPins(text)
        merged = {k: v for k, v in old.items() if k not in rejects and k not in label}
        dropped = sorted(set(old) - set(merged))
        for k, v in pins.items():
            if k not in dropped:
                merged.setdefault(k, v)
        io.open(PATH, "w", encoding="utf-8", newline="").write(replaceBlock(text, block(merged)))
        print(f"[data_checks] pins: {len(set(merged) - set(old)):,} new, "
              f"{len(dropped):,} dropped ({len(label):,} venue-label sized, the rest "
              f"because their field still reads 9%+ off its own level at the "
              f"pinned distance), {len(merged):,} in the block")
        for k in dropped[:20]:
            print(f"    dropped {k}: was {old[k]:g} m")
    else:
        print(f"[data_checks] {PATH} missing -- pins not written")


def purgeLabelPins(getConn):
    """--purge-label-pins: take the venue-label sized pins out of the sticky
    block now, without running the checks (a minute, not half an hour). The
    ratings move on the next run from 04g1, or the nightly backfill."""
    if not os.path.exists(PATH):
        print(f"[data_checks] {PATH} missing")
        return
    text = io.open(PATH, encoding="utf-8", newline="").read()
    old = readPins(text)
    with getConn() as c, c.cursor() as cur:
        label = labelPins(cur, old)
        c.rollback()
    for k in sorted(label):
        print(f"    dropped {k}: was {old[k]:g} m")
    keep = {k: v for k, v in old.items() if k not in label}
    io.open(PATH, "w", encoding="utf-8", newline="").write(replaceBlock(text, block(keep)))
    print(f"[data_checks] {len(label):,} venue-label pins dropped, {len(keep):,} kept")


