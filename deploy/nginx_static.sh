#!/usr/bin/env bash
# deploy/nginx_static.sh -- nginx sends the pre-rendered pages itself
# (racecast/build_static_pages.py); everything else still reaches gunicorn.
#
#   sudo bash deploy/nginx_static.sh            # install / update (idempotent), then verify
#   sudo bash deploy/nginx_static.sh --remove   # ROLLBACK: nginx proxies everything again
#
# ★ WHAT IT WRITES (and nothing else):
#   /etc/nginx/conf.d/racecast-static.conf    the maps (http level)
#   /etc/nginx/snippets/racecast-static.conf  three stat()s and two internal locations
#   one `include` line, marked "# racecast-static (deploy/nginx_static.sh)",
#     at the top of each server { } in the site file that proxies to
#     127.0.0.1:8000 (the TLS block certbot wrote); a backup of the site file
#     is kept beside it (.bak-static)
#   /var/cache/racecast-static, owned by the site user (xcp)
#   Both config files are GENERATED by the builder from the app's own header
#   values, so they cannot drift: a changed XCP_PAGE_S_MAXAGE changes the
#   signature line, and the builder publishes nothing until this is re-run.
#
# ★ IT CHECKS ITSELF. With XCP_STATIC_PAGES=1 in /etc/xc-predictor.env it
#   builds once and asks nginx for every built URL twice -- as a file, and
#   through the app (X-Racecast-Static: 1) -- plain, gzip and HEAD. One
#   difference in a body or a header and it takes itself out again (--remove)
#   and prints what differed. Without the flag it installs and serves nothing
#   (no files are written), and says so.
#
# ! THE ROLLBACK IS ONE LINE: sudo bash deploy/nginx_static.sh --remove
#   (or, without this script: XCP_STATIC_PAGES=0 -- the next timer run clears
#   every window -- or `rm -rf /var/cache/racecast-static/b/*`, which nginx
#   notices on the very next request).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PY="${XCP_PYTHON:-/srv/venv/bin/python}"
SITE="${XCP_NGINX_SITE:-/etc/nginx/sites-available/xc-predictor}"
HTTP_CONF=/etc/nginx/conf.d/racecast-static.conf
SNIPPET="${XCP_STATIC_NGINX_SNIPPET:-/etc/nginx/snippets/racecast-static.conf}"
DIR="${XCP_STATIC_DIR:-/var/cache/racecast-static}"
SITE_USER="${XCP_SITE_USER:-xcp}"
BUILDER="$ROOT/racecast/build_static_pages.py"

if [ -f /etc/xc-predictor.env ]; then
  set -a; . /etc/xc-predictor.env; set +a
fi
export XCP_STATIC_DIR="$DIR" XCP_STATIC_NGINX_SNIPPET="$SNIPPET" XCP_PREWARM=0
# the site's own database settings: a small pool, the site's timeouts
export XCP_DB_APP=site XCP_DB_MIN_CONN=1 XCP_DB_MAX_CONN=2
export XCP_DB_LOCK_TIMEOUT_MS=5000 XCP_DB_STATEMENT_TIMEOUT_MS=55000

remove() {
  [ -f "$SITE" ] && "$PY" "$BUILDER" --unpatch-site "$SITE" || true
  rm -f "$HTTP_CONF" "$SNIPPET"
  [ -d "$DIR" ] && "$PY" "$BUILDER" --clear --dir "$DIR" 2>/dev/null || true
  nginx -t && systemctl reload nginx
  echo "removed: nginx proxies every request to the app again"
}

if [ "${1:-}" = "--remove" ]; then
  remove; exit 0
fi

[ -f "$SITE" ] || { echo "STOP: no site file at $SITE (set XCP_NGINX_SITE)" >&2; exit 1; }

# the gzip_min_length nginx applies to the app's answers (nginx's own
# default is 20 when nothing sets it); the builder sends a short answer
# from a location with gzip off, so the two compress alike
GZ="$(nginx -T 2>/dev/null | grep -vE '^\s*#' | grep -E '^\s*gzip_min_length\s' | head -1 \
      | awk '{print $2}' | tr -d ';' || true)"
export XCP_STATIC_GZIP_MIN_LENGTH="${GZ:-20}"

install -d -m 755 -o "$SITE_USER" -g "$SITE_USER" "$DIR"
mkdir -p "$(dirname "$SNIPPET")"
cp -p "$SITE" "$SITE.bak-static"

cd "$ROOT"
"$PY" "$BUILDER" --print-nginx http   > "$HTTP_CONF.new"
"$PY" "$BUILDER" --print-nginx server > "$SNIPPET.new"
mv "$HTTP_CONF.new" "$HTTP_CONF"
mv "$SNIPPET.new" "$SNIPPET"
"$PY" "$BUILDER" --patch-site "$SITE"

if ! nginx -t; then
  echo "nginx -t refused the static config; putting everything back" >&2
  cp -p "$SITE.bak-static" "$SITE"
  rm -f "$HTTP_CONF" "$SNIPPET"
  nginx -t && systemctl reload nginx
  exit 1
fi
systemctl reload nginx
echo "installed: $HTTP_CONF, $SNIPPET, include in $SITE (gzip_min_length $XCP_STATIC_GZIP_MIN_LENGTH)"

if [ "${XCP_STATIC_PAGES:-0}" != "1" ]; then
  echo "XCP_STATIC_PAGES is not 1 in /etc/xc-predictor.env: no files are built, so nginx"
  echo "sends every request to the app as before. To switch it on: add XCP_STATIC_PAGES=1,"
  echo "run this script again (it builds and verifies), then deploy/install_static_timer.sh."
  exit 0
fi

# build once as the site user, then compare every URL: file vs app
sudo -E -u "$SITE_USER" "$PY" -u "$BUILDER"
BASE="${XCP_STATIC_VERIFY_BASE:-https://127.0.0.1}"
if ! sudo -E -u "$SITE_USER" "$PY" -u "$BUILDER" --verify "$BASE"; then
  echo "A FILE DIFFERED FROM THE APP'S ANSWER (above). Taking the static config out again." >&2
  remove
  exit 1
fi
echo "verified: every built URL is byte-identical through nginx, as a file and from the app"
